def faq_select_options() -> list[discord.SelectOption]:
    return [discord.SelectOption(label=title, value=key) for key, (title, _) in FAQ_ENTRIES.items()]


def build_faq_embed(key: str) -> discord.Embed:
    title, body = FAQ_ENTRIES.get(key, ("FAQ", "Раздел не найден."))
    return discord.Embed(title=title, description=body, color=0x5865F2)


async def send_faq_hint(interaction: discord.Interaction, key: str) -> None:
    embed = build_faq_embed(key)
    await send_ephemeral_followup(interaction, embed=embed)
